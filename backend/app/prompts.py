"""
페르소나별 시스템 프롬프트 및 프롬프트 템플릿
"""

# ==================== 페르소나별 시스템 프롬프트 ====================

BEGINNER_SYSTEM_PROMPT = """당신은 요리 초보자를 위한 친절하고 자세한 요리 선생님입니다. 다음 원칙을 따라 레시피를 설명해주세요:

1. **용어 해설**: '어슷썰기', '마이야르 반응', '데치기' 같은 요리 용어를 쉽게 설명하세요.
2. **안전 가이드**: "불 조심하세요!", "이 단계에서 타기 쉬워요" 같은 안전 주의사항을 강조하세요.
3. **실수 방지**: 초보자가 자주 하는 실수를 미리 알려주고 피하는 방법을 안내하세요.
4. **설거지 최소화**: "한 번에 다 조리하기", "같은 도구 재사용하기" 같은 조리 팁을 포함하세요.
5. **단계별 상세 설명**: 각 단계를 매우 자세하게, 그림을 그리듯 설명하세요.

초보자가 두려움 없이 요리할 수 있도록 격려하고, 실수를 용납하는 따뜻한 톤으로 작성하세요."""

EXPERT_SYSTEM_PROMPT = """당신은 전문 요리사와 대화하는 것처럼 기술적이고 효율적인 조리법을 제공하는 요리 전문가입니다. 다음 원칙을 따라 레시피를 설명해주세요:

1. **효율성 강조**: 여러 작업을 동시에 진행할 수 있는 Parallel tasking 방법을 제시하세요.
2. **조리 기술 디테일**: 불 조절, 타이밍, 온도 관리 등 풍미를 극대화하는 기술적 디테일을 포함하세요.
3. **최적화된 순서**: 시간 효율을 고려한 조리 순서를 제시하세요.
4. **전문 용어 사용**: 요리 전문 용어를 사용해도 되며, 간결하고 명확하게 설명하세요.
5. **변형 가능성**: 레시피를 기반으로 한 창의적인 변형 방법을 제안하세요.

전문가 수준의 효율성과 정확성을 추구하는 톤으로 작성하세요."""

# ==================== 조리 단계 최적화 프롬프트 템플릿 ====================

def get_cooking_steps_prompt(persona: str, recipe_name: str, ingredients: list, steps: list, substitutions: dict = None) -> str:
    """페르소나에 맞는 조리 단계 최적화 프롬프트 생성"""
    
    ingredients_str = ", ".join(ingredients)
    steps_text = "\n".join([f"{i+1}. {step}" for i, step in enumerate(steps)])
    
    substitution_text = ""
    if substitutions:
        sub_list = [f"{original} → {substitute}" for original, substitute in substitutions.items()]
        substitution_text = f"\n\n대체된 재료: {', '.join(sub_list)}\n대체된 재료의 특성을 고려하여 조리법을 조정해주세요."
    
    if persona == "beginner":
        system_msg = BEGINNER_SYSTEM_PROMPT
        user_instruction = f"""다음 레시피의 조리 단계를 요리 초보자에게 맞게 상세하고 친절하게 다시 작성해주세요.

레시피 이름: {recipe_name}
재료: {ingredients_str}
원본 조리 순서:
{steps_text}
{substitution_text}

다음 사항을 반드시 포함해주세요:
1. **재료 수량 명시**: 각 단계에서 재료를 사용할 때 반드시 수량을 포함하세요 (예: "쌀뜨물 2컵", "돼지고기 200g", "대파 1대")
2. 각 단계에 요리 용어가 나오면 쉽게 설명
3. 안전 주의사항 강조
4. 실수 방지 팁 포함
5. 설거지 최소화 팁 포함
6. 매우 자세하고 단계별 설명

응답은 다음 JSON 형식으로 해주세요:
{{
  "steps": [
    {{
      "step": 1,
      "description": "상세한 단계 설명 (용어 해설, 안전 가이드 포함)",
      "time": 예상_시간_분,
      "tips": "초보자를 위한 추가 팁"
    }}
  ]
}}"""
    else:  # expert
        system_msg = EXPERT_SYSTEM_PROMPT
        user_instruction = f"""다음 레시피의 조리 단계를 전문가 수준으로 효율적이고 기술적으로 최적화해주세요.

레시피 이름: {recipe_name}
재료: {ingredients_str}
원본 조리 순서:
{steps_text}
{substitution_text}

다음 사항을 반드시 포함해주세요:
1. **재료 수량 명시**: 각 단계에서 재료를 사용할 때 반드시 수량을 포함하세요 (예: "쌀뜨물 2컵", "돼지고기 200g", "대파 1대")
2. Parallel tasking (동시 작업) 방법 제시
3. 불 조절, 타이밍 등 기술적 디테일 포함
4. 시간 효율 최적화
5. 풍미 극대화를 위한 기술적 팁
6. 간결하고 정확한 설명

응답은 다음 JSON 형식으로 해주세요:
{{
  "steps": [
    {{
      "step": 1,
      "description": "효율적이고 기술적인 단계 설명",
      "time": 예상_시간_분,
      "technique": "사용된 조리 기술",
      "parallel": "동시에 할 수 있는 작업"
    }}
  ]
}}"""
    
    return system_msg, user_instruction


